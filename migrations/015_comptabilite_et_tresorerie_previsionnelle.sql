-- Migration 015 : comptabilité du siège (CA et FEES à refacturer) et trésorerie prévisionnelle (lot 24, décision 0018).
-- SQL standard PostgreSQL, rejouable. S'ajoute aux migrations 001 à 014 sans remise à zéro.
--
-- fees_rubriques         : colonnes de la refacturation (droit de marque, management fees...). Base « CA » (comptée
--                          dans le total refacturé) ou base « RUBRIQUE » (répartition d'une rubrique de base CA :
--                          compta, communication... ; détaille le total sans s'y ajouter). Code stable.
--                          Lecture : toute personne active ; écriture : administrateur.
-- fees_regles            : versions datées (mois d'effet) des taux ou montants bruts, pour le groupe (dossier « * »)
--                          ou une résidence. Mode « groupe » : la résidence revient à la règle du groupe.
--                          Lecture : règles du groupe pour toute personne active, règles d'une résidence selon le parc ;
--                          écriture : administrateur.
-- ca_regles              : comptes retenus pour le CA (préfixes inclus et exclus), pour le groupe (« * ») ou une
--                          résidence. Sans règle : tous les comptes 7. Lecture et écriture comme fees_regles.
-- fees_clotures          : instantané figé d'un mois refacturé (CA, règles et montants). Jamais modifié : on rouvre
--                          (suppression) puis on clôture de nouveau. Lecture selon le parc ; administrateur seulement.
-- compta_journal         : chaque création, modification ou suppression des quatre tables ci-dessus (avant, après,
--                          auteur, date), écrit par la base seule. Lecture : administrateur.
-- comptes_bancaires      : + solde_max (plafond) pour proposer la remontée de l'excédent vers le compte principal.
-- tresorerie_previsions  : encaissements et décaissements prévus saisis par le trésorier (ponctuels ou mensuels),
--                          sur un compte bancaire d'une résidence. Administrateur seulement.
-- virements_suivis       : virements de compte à compte d'une même résidence marqués « faits » par le trésorier.
--                          Administrateur seulement. Aucun virement entre résidences (décision 0018).

CREATE TABLE IF NOT EXISTS fees_rubriques (
    code          text PRIMARY KEY CHECK (code ~ '^[A-Z0-9_]{2,40}$'),
    libelle       text NOT NULL CHECK (length(libelle) BETWEEN 1 AND 60),
    base          text NOT NULL CHECK (base IN ('CA', 'RUBRIQUE')),
    base_rubrique text REFERENCES fees_rubriques(code) ON UPDATE CASCADE,
    ordre         integer NOT NULL DEFAULT 0,
    actif         boolean NOT NULL DEFAULT true,
    modifie_par   text,
    modifie_le    timestamptz NOT NULL DEFAULT now(),
    CHECK ((base = 'CA') = (base_rubrique IS NULL)),
    CHECK (base_rubrique IS NULL OR base_rubrique <> code)
);

CREATE TABLE IF NOT EXISTS fees_regles (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rubrique    text NOT NULL REFERENCES fees_rubriques(code) ON UPDATE CASCADE,
    dossier     text NOT NULL CHECK (dossier = '*' OR dossier ~ '^[A-Z0-9_-]+$'),
    mois_effet  text NOT NULL CHECK (mois_effet ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    mode        text NOT NULL CHECK (mode IN ('taux', 'montant', 'groupe')),
    valeur      numeric,
    modifie_par text,
    modifie_le  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (rubrique, dossier, mois_effet),
    CHECK ((mode = 'groupe') = (valeur IS NULL)),
    CHECK (mode <> 'groupe' OR dossier <> '*'),
    CHECK (mode <> 'taux' OR (valeur BETWEEN -1000 AND 1000 AND valeur = round(valeur, 4))),
    CHECK (mode <> 'montant' OR (abs(valeur) < 100000000 AND valeur = round(valeur, 2)))
);

CREATE TABLE IF NOT EXISTS ca_regles (
    dossier     text PRIMARY KEY CHECK (dossier = '*' OR dossier ~ '^[A-Z0-9_-]+$'),
    inclus      text[] NOT NULL CHECK (cardinality(inclus) BETWEEN 1 AND 50
                                       AND array_to_string(inclus, ',') ~ '^[0-9]{1,10}(,[0-9]{1,10})*$'),
    exclus      text[] NOT NULL DEFAULT '{}' CHECK (cardinality(exclus) <= 50
                                       AND array_to_string(exclus, ',') ~ '^([0-9]{1,10}(,[0-9]{1,10})*)?$'),
    modifie_par text,
    modifie_le  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fees_clotures (
    dossier  text NOT NULL CHECK (dossier ~ '^[A-Z0-9_-]+$'),
    mois     text NOT NULL CHECK (mois ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    contenu  jsonb NOT NULL CHECK (jsonb_typeof(contenu) = 'object' AND contenu ? 'lignes' AND contenu ? 'total'),
    clos_par text,
    clos_le  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (dossier, mois)
);

CREATE TABLE IF NOT EXISTS compta_journal (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objet  text NOT NULL CHECK (objet IN ('rubrique', 'regle', 'regle_ca', 'cloture')),
    cle    text NOT NULL,
    action text NOT NULL CHECK (action IN ('création', 'modification', 'suppression')),
    avant  jsonb,
    apres  jsonb,
    par    text,
    le     timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE comptes_bancaires ADD COLUMN IF NOT EXISTS solde_max bigint;
ALTER TABLE comptes_bancaires DROP CONSTRAINT IF EXISTS comptes_bancaires_plafond;
ALTER TABLE comptes_bancaires ADD CONSTRAINT comptes_bancaires_plafond
  CHECK (solde_max IS NULL OR (solde_max >= 0 AND (solde_min IS NULL OR solde_max >= solde_min)));

CREATE TABLE IF NOT EXISTS tresorerie_previsions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier     text NOT NULL CHECK (dossier ~ '^[A-Z0-9_-]+$'),
    compte      text NOT NULL CHECK (compte ~ '^5[0-9A-Z]*$'),
    libelle     text NOT NULL CHECK (length(libelle) BETWEEN 1 AND 80),
    sens        text NOT NULL CHECK (sens IN ('enc', 'dec')),
    montant     bigint NOT NULL CHECK (montant > 0),
    date_prevue date NOT NULL,
    recurrence  text NOT NULL DEFAULT 'aucune' CHECK (recurrence IN ('aucune', 'mensuelle')),
    jusqu_au    date,
    actif       boolean NOT NULL DEFAULT true,
    modifie_par text,
    modifie_le  timestamptz NOT NULL DEFAULT now(),
    CHECK (jusqu_au IS NULL OR (recurrence = 'mensuelle' AND jusqu_au >= date_prevue))
);

CREATE TABLE IF NOT EXISTS virements_suivis (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier       text NOT NULL CHECK (dossier ~ '^[A-Z0-9_-]+$'),
    compte_de     text NOT NULL CHECK (compte_de ~ '^5[0-9A-Z]*$'),
    compte_vers   text NOT NULL CHECK (compte_vers ~ '^5[0-9A-Z]*$'),
    montant       bigint NOT NULL CHECK (montant > 0),
    date_virement date NOT NULL,
    note          text NOT NULL DEFAULT '' CHECK (length(note) <= 200),
    fait_par      text,
    fait_le       timestamptz NOT NULL DEFAULT now(),
    CHECK (compte_de <> compte_vers)
);

-- Contrôles des rubriques : une répartition porte sur une rubrique de base CA (un seul niveau) ; une rubrique
-- de base CA qui a des répartitions ne peut pas devenir elle-même une répartition.
CREATE OR REPLACE FUNCTION controle_fees_rubrique() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.base = 'RUBRIQUE' THEN
    IF NOT EXISTS (SELECT 1 FROM fees_rubriques r WHERE r.code = NEW.base_rubrique AND r.base = 'CA') THEN
      RAISE EXCEPTION 'Rubrique % : sa base doit être une rubrique calculée sur le CA.', NEW.code USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM fees_rubriques r WHERE r.base_rubrique = NEW.code) THEN
      RAISE EXCEPTION 'Rubrique % : elle est la base d''autres rubriques, elle doit rester calculée sur le CA.', NEW.code USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  NEW.modifie_par := coalesce(email_courant(), NEW.modifie_par);
  NEW.modifie_le := now();
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS fees_rubriques_controle ON fees_rubriques;
CREATE TRIGGER fees_rubriques_controle BEFORE INSERT OR UPDATE ON fees_rubriques
  FOR EACH ROW EXECUTE FUNCTION controle_fees_rubrique();

CREATE OR REPLACE FUNCTION trace_compta() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.modifie_par := coalesce(email_courant(), NEW.modifie_par);
  NEW.modifie_le := now();
  RETURN NEW;
END
$$;
