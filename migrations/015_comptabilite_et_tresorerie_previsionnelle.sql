-- Journal écrit par la base seule (personne ne peut y écrire directement).
CREATE OR REPLACE FUNCTION journal_compta() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  o jsonb := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  objet text := CASE TG_TABLE_NAME WHEN 'fees_rubriques' THEN 'rubrique' WHEN 'fees_regles' THEN 'regle'
                                   WHEN 'ca_regles' THEN 'regle_ca' ELSE 'cloture' END;
  cle text := CASE TG_TABLE_NAME WHEN 'fees_rubriques' THEN o ->> 'code'
                                 WHEN 'fees_regles' THEN concat_ws('|', o ->> 'rubrique', o ->> 'dossier', o ->> 'mois_effet')
                                 WHEN 'ca_regles' THEN o ->> 'dossier'
                                 ELSE concat_ws('|', o ->> 'dossier', o ->> 'mois') END;
BEGIN
  INSERT INTO compta_journal (objet, cle, action, avant, apres, par)
  VALUES (objet, cle,
          CASE TG_OP WHEN 'INSERT' THEN 'création' WHEN 'UPDATE' THEN 'modification' ELSE 'suppression' END,
          CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE to_jsonb(OLD) END,
          CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE to_jsonb(NEW) END,
          email_courant());
  RETURN NULL;
END
$$;
DROP TRIGGER IF EXISTS fees_rubriques_journal ON fees_rubriques;
CREATE TRIGGER fees_rubriques_journal AFTER INSERT OR UPDATE OR DELETE ON fees_rubriques FOR EACH ROW EXECUTE FUNCTION journal_compta();
