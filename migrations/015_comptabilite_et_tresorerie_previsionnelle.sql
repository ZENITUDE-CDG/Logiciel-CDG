-- Une clôture est figée : auteur et date posés par la base, aucune modification (rouvrir = supprimer).
CREATE OR REPLACE FUNCTION garde_cloture() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION 'Une clôture ne se modifie pas : rouvrez le mois puis clôturez-le de nouveau.' USING ERRCODE = 'check_violation';
  END IF;
  NEW.clos_par := coalesce(email_courant(), NEW.clos_par);
  NEW.clos_le := now();
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS fees_clotures_garde ON fees_clotures;
CREATE TRIGGER fees_clotures_garde BEFORE INSERT OR UPDATE ON fees_clotures FOR EACH ROW EXECUTE FUNCTION garde_cloture();

CREATE OR REPLACE FUNCTION trace_virement() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.fait_par := coalesce(email_courant(), NEW.fait_par);
  NEW.fait_le := now();
  RETURN NEW;
END
$$;
