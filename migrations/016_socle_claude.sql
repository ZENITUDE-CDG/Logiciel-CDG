CREATE POLICY missions_claude_admin ON missions_claude FOR ALL TO authenticated
  USING (est_administrateur()) WITH CHECK (est_administrateur());

DROP POLICY IF EXISTS missions_versions_lecture ON missions_versions;
CREATE POLICY missions_versions_lecture ON missions_versions FOR SELECT TO authenticated USING (role_courant() IS NOT NULL);

DROP POLICY IF EXISTS paquets_claude_lecture ON paquets_claude;
CREATE POLICY paquets_claude_lecture ON paquets_claude FOR SELECT TO authenticated
  USING (est_administrateur() OR (role_courant() IS NOT NULL AND cree_par = email_courant()));
DROP POLICY IF EXISTS paquets_claude_ajout ON paquets_claude;
CREATE POLICY paquets_claude_ajout ON paquets_claude FOR INSERT TO authenticated
  WITH CHECK (role_courant() IS NOT NULL
              AND NOT EXISTS (SELECT 1 FROM unnest(dossiers) AS x(d) WHERE NOT voit_dossier(x.d)));
DROP POLICY IF EXISTS paquets_claude_resultat ON paquets_claude;
CREATE POLICY paquets_claude_resultat ON paquets_claude FOR UPDATE TO authenticated
  USING (est_administrateur() OR (role_courant() IS NOT NULL AND cree_par = email_courant()))
  WITH CHECK (est_administrateur() OR (role_courant() IS NOT NULL AND cree_par = email_courant()));

GRANT SELECT, INSERT, UPDATE, DELETE ON missions_claude TO authenticated;
GRANT SELECT ON missions_versions TO authenticated;
GRANT SELECT, INSERT, UPDATE ON paquets_claude TO authenticated;
