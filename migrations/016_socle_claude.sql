-- Migration 016 : socle de données pour Claude et missions (lot 25, décision 0019).
-- SQL standard PostgreSQL, rejouable. S'ajoute aux migrations 001 à 015 sans remise à zéro.
--
-- Le paquet de données lui-même n'est jamais stocké : la page le construit à partir des chiffres publiés que la
-- personne a le droit de voir, et le télécharge. La base garde seulement des textes et un journal sans montant :
--
-- missions_claude   : cahiers des charges réutilisables (méthode, hypothèses, livrables), sans chiffre réel, en
--                     nombre illimité, rangés par catégorie, identifiés par un code stable. Chaque modification du
--                     titre, du code, des consignes ou des livrables incrémente la version.
--                     Lecture : toute personne active ; écriture : administrateur. Auteur et date posés par la base.
-- missions_versions : versions précédentes de chaque mission, écrites par la base seule (jamais modifiées).
--                     Lecture : toute personne active.
-- paquets_claude    : journal des paquets préparés : référence (PQ-000001, citée dans chaque document produit),
--                     empreinte SHA-256 des données, périmètre, période, niveau, mission et version utilisées, puis
--                     le document produit (lien ou nom) noté après coup. Aucun montant.
--                     Ajout : toute personne active, pour des résidences de son parc ; seuls le document produit et sa
--                     note se modifient ensuite (auteur du paquet ou administrateur) ; jamais supprimé.
--                     Lecture : ses propres paquets ; administrateur : tous.

CREATE TABLE IF NOT EXISTS missions_claude (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text NOT NULL UNIQUE CHECK (code ~ '^[A-Z0-9_-]{2,40}$'),
    categorie   text NOT NULL DEFAULT '' CHECK (length(categorie) <= 60),
    titre       text NOT NULL CHECK (length(btrim(titre)) BETWEEN 1 AND 120),
    description text NOT NULL DEFAULT '' CHECK (length(description) <= 300),
    consignes   text NOT NULL CHECK (length(btrim(consignes)) BETWEEN 1 AND 60000),
    livrables   text NOT NULL DEFAULT '' CHECK (length(livrables) <= 10000),
    actif       boolean NOT NULL DEFAULT true,
    version     integer NOT NULL DEFAULT 1 CHECK (version >= 1),
    modifie_par text,
    modifie_le  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS missions_versions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id  bigint NOT NULL REFERENCES missions_claude(id) ON DELETE CASCADE,
    version     integer NOT NULL,
    code        text NOT NULL,
    titre       text NOT NULL,
    consignes   text NOT NULL,
    livrables   text NOT NULL DEFAULT '',
    modifie_par text,
    modifie_le  timestamptz NOT NULL,
    UNIQUE (mission_id, version)
);

CREATE TABLE IF NOT EXISTS paquets_claude (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference       text UNIQUE,
    perimetre       text NOT NULL CHECK (length(perimetre) BETWEEN 1 AND 200),
    dossiers        text[] NOT NULL CHECK (cardinality(dossiers) BETWEEN 1 AND 1000
                                          AND array_to_string(dossiers, ',') ~ '^[A-Z0-9_-]+(,[A-Z0-9_-]+)*$'),
    du              text NOT NULL CHECK (du ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    au              text NOT NULL CHECK (au ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    niveau          text NOT NULL CHECK (niveau IN ('complet', 'synthese')),
    empreinte       text NOT NULL CHECK (empreinte ~ '^[0-9a-f]{64}$'),
    mission_id      bigint REFERENCES missions_claude(id) ON DELETE SET NULL,
    mission_code    text CHECK (mission_code IS NULL OR mission_code ~ '^[A-Z0-9_-]{2,40}$'),
    mission_version integer CHECK (mission_version IS NULL OR mission_version >= 1),
    nb_fichiers     integer NOT NULL DEFAULT 0 CHECK (nb_fichiers BETWEEN 0 AND 100),
    resultat        text NOT NULL DEFAULT '' CHECK (length(resultat) <= 300),
    resultat_note   text NOT NULL DEFAULT '' CHECK (length(resultat_note) <= 1000),
    resultat_par    text,
    resultat_le     timestamptz,
    cree_par        text,
    cree_le         timestamptz NOT NULL DEFAULT now(),
    CHECK (du <= au),
    CHECK ((mission_code IS NULL) = (mission_version IS NULL))
);

-- Missions : auteur et date posés par la base ; une modification du contenu archive la version précédente.
CREATE OR REPLACE FUNCTION trace_mission_claude() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.id <> OLD.id THEN
      RAISE EXCEPTION 'L''identifiant d''une mission ne change pas.' USING ERRCODE = 'check_violation';
    END IF;
    IF (NEW.titre, NEW.code, NEW.consignes, NEW.livrables) IS DISTINCT FROM (OLD.titre, OLD.code, OLD.consignes, OLD.livrables) THEN
      INSERT INTO missions_versions (mission_id, version, code, titre, consignes, livrables, modifie_par, modifie_le)
      VALUES (OLD.id, OLD.version, OLD.code, OLD.titre, OLD.consignes, OLD.livrables, OLD.modifie_par, OLD.modifie_le);
      NEW.version := OLD.version + 1;
    ELSE
      NEW.version := OLD.version;
    END IF;
  ELSE
    NEW.version := 1;
  END IF;
  NEW.modifie_par := coalesce(email_courant(), NEW.modifie_par);
  NEW.modifie_le := now();
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS missions_claude_trace ON missions_claude;
CREATE TRIGGER missions_claude_trace BEFORE INSERT OR UPDATE ON missions_claude
  FOR EACH ROW EXECUTE FUNCTION trace_mission_claude();

-- Paquets : référence, auteur et date posés par la base ; ensuite seuls le document produit et sa note changent.
CREATE OR REPLACE FUNCTION trace_paquet_claude() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.reference := 'PQ-' || lpad(NEW.id::text, 6, '0');
    NEW.cree_par := coalesce(email_courant(), NEW.cree_par);
    NEW.cree_le := now();
    NEW.resultat := '';
    NEW.resultat_note := '';
    NEW.resultat_par := NULL;
    NEW.resultat_le := NULL;
    RETURN NEW;
  END IF;
  IF (NEW.id, NEW.reference, NEW.perimetre, NEW.dossiers, NEW.du, NEW.au, NEW.niveau, NEW.empreinte, NEW.mission_code,
      NEW.mission_version, NEW.nb_fichiers, NEW.cree_par, NEW.cree_le)
     IS DISTINCT FROM (OLD.id, OLD.reference, OLD.perimetre, OLD.dossiers, OLD.du, OLD.au, OLD.niveau, OLD.empreinte, OLD.mission_code,
      OLD.mission_version, OLD.nb_fichiers, OLD.cree_par, OLD.cree_le) THEN
    RAISE EXCEPTION 'Seuls le document produit et sa note se modifient dans le journal des paquets.' USING ERRCODE = 'check_violation';
  END IF;
  NEW.resultat_par := email_courant();
  NEW.resultat_le := now();
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS paquets_claude_trace ON paquets_claude;
CREATE TRIGGER paquets_claude_trace BEFORE INSERT OR UPDATE ON paquets_claude
  FOR EACH ROW EXECUTE FUNCTION trace_paquet_claude();

ALTER TABLE missions_claude ENABLE ROW LEVEL SECURITY;
ALTER TABLE missions_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE paquets_claude ENABLE ROW LEVEL SECURITY;

