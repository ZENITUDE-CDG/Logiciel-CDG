-- Migration 019 : analyse des écarts (lots 28 à 30, décision 0022).
-- SQL standard PostgreSQL, rejouable. S'ajoute aux migrations 001 à 018 sans remise à zéro.
--
-- Les écarts eux-mêmes ne sont jamais stockés : la page les recalcule à partir des chiffres publiés (même calcul
-- que zenitude/analyse/ecarts.py). La base garde seulement ce que les personnes en disent :
--
-- ecarts_suivi      : un écart repéré (clé stable : code, résidence, objet, période, référence), son statut
--                     (à analyser, expliqué, à corriger, corrigé), le commentaire et le montant de l'écart au
--                     moment du commentaire (pour signaler un montant qui a changé depuis). Auteur et date posés
--                     par la base. Lecture : résidence du parc ; écriture : administrateur ou collaborateur sur
--                     une résidence de son parc ; lecture seule : rien. Jamais supprimé par un collaborateur.
-- ecarts_journal    : chaque changement de statut ou de commentaire, écrit par la base (aucune écriture directe).
-- analyse_parametres: seuils de l'analyse et référence proposée par défaut (une seule ligne, id 1). Lecture : toute
--                     personne active ; modification : administrateurs.
-- paquets_claude    : niveau « ecarts » accepté (paquet d'écarts préparé pour Claude, même traçabilité PQ).

CREATE TABLE IF NOT EXISTS ecarts_suivi (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cle          text NOT NULL UNIQUE CHECK (length(cle) BETWEEN 5 AND 300 AND cle ~ '^[A-Z][0-9]\|'),
    dossier      text NOT NULL CHECK (dossier ~ '^[A-Z0-9_-]+$'),
    code         text NOT NULL CHECK (code ~ '^[A-Z][0-9]$'),
    du           text NOT NULL CHECK (du ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    au           text NOT NULL CHECK (au ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    reference    text NOT NULL CHECK (reference IN ('n1', 'prec', 'moy12')),
    statut       text NOT NULL DEFAULT 'a_analyser' CHECK (statut IN ('a_analyser', 'explique', 'a_corriger', 'corrige')),
    commentaire  text NOT NULL DEFAULT '' CHECK (length(commentaire) <= 2000),
    montant      bigint,
    cree_par     text,
    cree_le      timestamptz NOT NULL DEFAULT now(),
    modifie_par  text,
    modifie_le   timestamptz NOT NULL DEFAULT now(),
    CHECK (du <= au),
    CHECK (split_part(cle, '|', 1) = code AND split_part(cle, '|', 2) = dossier)
);
CREATE INDEX IF NOT EXISTS ecarts_suivi_dossier ON ecarts_suivi (dossier);

CREATE TABLE IF NOT EXISTS ecarts_journal (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suivi_id    bigint NOT NULL,
    cle         text NOT NULL,
    dossier     text NOT NULL,
    action      text NOT NULL,
    statut      text,
    commentaire text,
    montant     bigint,
    par         text,
    le          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ecarts_journal_dossier ON ecarts_journal (dossier);

CREATE TABLE IF NOT EXISTS analyse_parametres (
    id          integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    seuils      jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(seuils) = 'object' AND octet_length(seuils::text) <= 4000),
    reference   text NOT NULL DEFAULT 'n1' CHECK (reference IN ('n1', 'prec', 'moy12')),
    modifie_par text,
    modifie_le  timestamptz NOT NULL DEFAULT now()
);
INSERT INTO analyse_parametres (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- Auteur, dates et journal posés par la base ; la clé, la résidence, le code et la période ne changent jamais.
CREATE OR REPLACE FUNCTION trace_ecart_suivi() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.cree_par := coalesce(email_courant(), NEW.cree_par);
    NEW.cree_le := now();
  ELSIF (NEW.cle, NEW.dossier, NEW.code, NEW.du, NEW.au, NEW.reference, NEW.cree_par, NEW.cree_le)
        IS DISTINCT FROM (OLD.cle, OLD.dossier, OLD.code, OLD.du, OLD.au, OLD.reference, OLD.cree_par, OLD.cree_le) THEN
    RAISE EXCEPTION 'Seuls le statut, le commentaire et le montant d’un écart se modifient.' USING ERRCODE = 'check_violation';
  END IF;
  NEW.modifie_par := coalesce(email_courant(), NEW.modifie_par);
  NEW.modifie_le := now();
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS ecarts_suivi_trace ON ecarts_suivi;
CREATE TRIGGER ecarts_suivi_trace BEFORE INSERT OR UPDATE ON ecarts_suivi FOR EACH ROW EXECUTE FUNCTION trace_ecart_suivi();

CREATE OR REPLACE FUNCTION journal_ecart_suivi() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    INSERT INTO ecarts_journal (suivi_id, cle, dossier, action, statut, commentaire, montant, par)
    VALUES (OLD.id, OLD.cle, OLD.dossier, 'suppression', OLD.statut, OLD.commentaire, OLD.montant, email_courant());
    RETURN OLD;
  END IF;
  IF TG_OP = 'INSERT' OR (NEW.statut, NEW.commentaire) IS DISTINCT FROM (OLD.statut, OLD.commentaire) THEN
    INSERT INTO ecarts_journal (suivi_id, cle, dossier, action, statut, commentaire, montant, par)
    VALUES (NEW.id, NEW.cle, NEW.dossier, lower(TG_OP), NEW.statut, NEW.commentaire, NEW.montant, NEW.modifie_par);
  END IF;
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS ecarts_suivi_journal ON ecarts_suivi;
CREATE TRIGGER ecarts_suivi_journal AFTER INSERT OR UPDATE OR DELETE ON ecarts_suivi FOR EACH ROW EXECUTE FUNCTION journal_ecart_suivi();

CREATE OR REPLACE FUNCTION trace_analyse_parametres() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE k text;
BEGIN
  FOR k IN SELECT jsonb_object_keys(NEW.seuils) LOOP
    IF k NOT IN ('pct', 'montant', 'sigma', 'ecriture', 'coherence', 'rapprochement', 'etalement', 'historique') THEN
      RAISE EXCEPTION 'Seuil inconnu : %', k USING ERRCODE = 'check_violation';
    END IF;
    IF jsonb_typeof(NEW.seuils -> k) <> 'number' OR (NEW.seuils ->> k)::numeric < 0 THEN
      RAISE EXCEPTION 'Seuil % : un nombre positif.', k USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;
  NEW.modifie_par := coalesce(email_courant(), NEW.modifie_par);
  NEW.modifie_le := now();
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS analyse_parametres_trace ON analyse_parametres;
CREATE TRIGGER analyse_parametres_trace BEFORE INSERT OR UPDATE ON analyse_parametres FOR EACH ROW EXECUTE FUNCTION trace_analyse_parametres();

